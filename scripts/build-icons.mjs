// Writes src/renderer/js/icons.js from Lucide (ISC) and the real Claude
// mark from Simple Icons (CC0). Run again after changing the list:
//   node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lucide = join(root, 'node_modules', 'lucide-static', 'icons');

// name in the app -> Lucide icon
const LUCIDE = {
  compose: 'square-pen',
  folderPlus: 'folder-plus',
  folder: 'folder',
  gear: 'settings',
  chat: 'message-square',
  terminal: 'square-terminal',
  plus: 'plus',
  x: 'x',
  send: 'arrow-up',
  back: 'chevron-left',
  chevron: 'chevron-down',
  effort: 'gauge',
  mic: 'mic',
  doc: 'file-text',
  globe: 'globe',
  prompt: 'terminal',
  more: 'ellipsis',
  person: 'square-user',
  app: 'app-window',
  play: 'play',
  restart: 'rotate-ccw',
  popout: 'external-link',
  console: 'panel-bottom',
};

function lucideSvg(name) {
  const svg = readFileSync(join(lucide, `${name}.svg`), 'utf8');
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
  return `<svg viewBox="0 0 24 24" aria-hidden="true" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
}

const { siClaude } = require('simple-icons');
const icons = Object.fromEntries(Object.entries(LUCIDE).map(([key, name]) => [key, lucideSvg(name)]));
icons.stop = '<svg viewBox="0 0 24 24" aria-hidden="true"><rect x="7" y="7" width="10" height="10" rx="2.5" fill="currentColor" /></svg>';
// The Claude spark, in Claude's own orange, no background.
icons.claude = `<svg viewBox="0 0 24 24" aria-hidden="true" class="claude-mark"><path fill="#${siClaude.hex}" d="${siClaude.path}" /></svg>`;

const out = `// Generated by scripts/build-icons.mjs from Lucide (ISC) and Simple Icons (CC0, the Claude mark).
// Don't edit by hand: change the list there and run it again.

export const icons = ${JSON.stringify(icons, null, 2)};
`;
writeFileSync(join(root, 'src', 'renderer', 'js', 'icons.js'), out);
console.log(`icons.js: ${Object.keys(icons).length} icons`);
